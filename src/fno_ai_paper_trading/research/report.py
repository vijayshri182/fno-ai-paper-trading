"""Concise HTML research-report builder.

Composes small, labelled sections (configuration, dataset, strategy
parameters, gross/net performance, costs, slippage, drawdown, trade stats,
benchmark, in-sample / out-of-sample, parameter sensitivity) into a single
self-contained HTML page. The builders here are intentionally generic so the
research scripts decide the content; this module only renders it.

All research output must be clearly labelled as historical/synthetic evidence.
"""
from __future__ import annotations

import html
from decimal import Decimal


def fmt(value: Decimal | None | float | int | str, suffix: str = "") -> str:
    """Format a metric for a report; None renders as 'n/a'."""
    if value is None:
        return "n/a"
    if isinstance(value, Decimal):
        if not value.is_finite():
            return "Infinity" if value > 0 else "-Infinity"
        return f"{value:f}{suffix}"
    return f"{value}{suffix}"


def escape(value: str) -> str:
    return html.escape(value)


def card(num: str, label: str, tone: str = "neutral") -> str:
    return f"<div class='card {tone}'><div class='num'>{escape(num)}</div><div class='lbl'>{escape(label)}</div></div>"


def kv_rows(pairs: list[tuple[str, str]]) -> str:
    return "".join(
        f"<tr><th>{escape(k)}</th><td class='num'>{escape(v)}</td></tr>" for k, v in pairs
    )


def table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{escape(h)}</th>" for h in headers)
    body = ""
    for row in rows:
        body += "<tr>" + "".join(f"<td class='num'>{escape(cell)}</td>" for cell in row) + "</tr>"
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


