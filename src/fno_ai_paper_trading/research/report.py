def build_research_html(
    *,
    title: str,
    blocks: list[str],
    disclaimer: str,
    generated_at: str,
) -> str:
    """Assemble a labelled research report page."""
    sections = "".join(blocks)
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<style>{CSS}</style>
</head>
<body>
<div class="wrap">
  <header>
    <h1>{escape(title)}</h1>
    <p>Generated {escape(generated_at)} &middot; paper-trading only &middot; deterministic synthetic data</p>
  </header>
  <div class="note"><strong>Disclaimer:</strong> {escape(disclaimer)}</div>
  {sections}
  <div class="footer">Generated by the strategy-research framework &middot; paper-trading only &middot; no secret data</div>
</div>
</body>
</html>"""


def metrics_cards(metrics) -> str:
    """A compact set of headline metric cards."""
    return "".join([
        card(fmt(metrics.net_pnl), "Net P&L", "ok" if (metrics.net_pnl or 0) >= 0 else "bad"),
        card(fmt(metrics.net_return_pct, "%"), "Net Return"),
        card(fmt(metrics.cagr_pct, "%"), "CAGR (annualized)"),
        card(fmt(metrics.max_drawdown), "Max Drawdown", "bad"),
        card(fmt(metrics.max_drawdown_pct, "%"), "Max DD %", "bad"),
        card(str(metrics.num_trades), "Trades"),
        card(fmt(metrics.expectancy), "Expectancy"),
        card(fmt(metrics.sharpe_ratio), "Sharpe (ann.)"),
    ])